namespace RollRadar.Api.Data;

// Training diary (RR-013). Every row belongs to one user, directly (user_id) or through its session; enum values
// are stored as snake_case strings, e.g. Attire.NoGi -> "no_gi", NodeSide.PorBaixo -> "por_baixo".

public enum Attire
{
    Gi,
    NoGi,
}

public enum TrainingFormat
{
    Aula,
    Open,
    Competicao,
}

public enum Belt
{
    Branca,
    Azul,
    Roxa,
    Marrom,
    Preta,
}

/// <summary>Where the user was in a position: on top, at the bottom, or neither (e.g. standing, 50/50).</summary>
public enum NodeSide
{
    PorCima,
    PorBaixo,
    Neutro,
}

/// <summary>How a position went in a roll: "fui bem", "estive" (just been there), "sofri".</summary>
public enum StepOutcome
{
    Bem,
    Neutro,
    Mal,
}

/// <summary>Answer to "did you work on the point to fix?": yes, partly, not yet.</summary>
public enum FocusReview
{
    Sim,
    Parcial,
    Nao,
}

/// <summary>One training session of a user.</summary>
public class TrainingSessionEntity
{
    /// <summary>Generated by the client, so sending the same session again does not create a second one.</summary>
    public Guid Id { get; set; }

    public Guid UserId { get; set; }
    public DateOnly Date { get; set; }
    public Attire Attire { get; set; }
    public TrainingFormat Format { get; set; }
    public int DurationMinutes { get; set; }

    /// <summary>What was taught or drilled, free text.</summary>
    public string? TechniqueNotes { get; set; }

    /// <summary>1 to 5, optional.</summary>
    public int? Sleep { get; set; }

    public int? Pain { get; set; }
    public int? Energy { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }

    public UserEntity? User { get; set; }
    public List<SessionTechniqueEntity> Techniques { get; set; } = [];
    public List<RollEntity> Rolls { get; set; } = [];
}

/// <summary>A catalog technique tagged on a session (the technique of the day).</summary>
public class SessionTechniqueEntity
{
    public Guid SessionId { get; set; }
    public required string TechniqueId { get; set; }

    /// <summary>Order the tags were added in.</summary>
    public int Position { get; set; }

    public TrainingSessionEntity? Session { get; set; }
    public TechniqueEntity? Technique { get; set; }
}

/// <summary>Someone the user rolls with; found again by name, ignoring case and accents.</summary>
public class PartnerEntity
{
    public long Id { get; set; }
    public Guid UserId { get; set; }

    /// <summary>As typed the last time.</summary>
    public required string Name { get; set; }

    /// <summary>Name after <see cref="Common.TextNormalizer.Normalize"/>, unique per user.</summary>
    public required string NormalizedName { get; set; }

    /// <summary>Latest belt, offered again in the next roll.</summary>
    public Belt? Belt { get; set; }

    public DateTime UpdatedAt { get; set; }

    public UserEntity? User { get; set; }
}

/// <summary>
/// One roll (sparring round) of a session. Rolls are usually timed, so one can have several submissions either way
/// (<see cref="Finishes"/>); none means nobody was submitted.
/// </summary>
public class RollEntity
{
    public long Id { get; set; }
    public Guid SessionId { get; set; }
    public int Order { get; set; }
    public long? PartnerId { get; set; }

    /// <summary>The partner's belt on that day (it changes over time).</summary>
    public Belt? PartnerBelt { get; set; }

    /// <summary>Length of the round, e.g. 5; optional.</summary>
    public int? DurationMinutes { get; set; }

    public string? Notes { get; set; }

    public TrainingSessionEntity? Session { get; set; }
    public PartnerEntity? Partner { get; set; }
    public List<RollStepEntity> Steps { get; set; } = [];
    public List<RollFinishEntity> Finishes { get; set; } = [];
}

/// <summary>A submission in a roll: by the user ("finalizei") or on the user ("fui finalizado").</summary>
public class RollFinishEntity
{
    public long Id { get; set; }
    public long RollId { get; set; }
    public int Order { get; set; }

    /// <summary>True when the user submitted the partner, false when the partner submitted the user.</summary>
    public bool ByMe { get; set; }

    /// <summary>The submission, optional; only chokes, arm locks and leg locks.</summary>
    public string? TechniqueId { get; set; }

    /// <summary>Position it came from, optional (one of the user's game nodes).</summary>
    public long? NodeId { get; set; }

    public RollEntity? Roll { get; set; }
    public TechniqueEntity? Technique { get; set; }
    public GameNodeEntity? Node { get; set; }
}

/// <summary>
/// A position of the user's game (a "Posições" or "Guardas" technique on one side), created the first time it is
/// marked in a roll. The connections between positions come with the game map (RR-014).
/// </summary>
public class GameNodeEntity
{
    public long Id { get; set; }
    public Guid UserId { get; set; }
    public required string TechniqueId { get; set; }

    /// <summary>The user's own name for it; null shows the technique's name.</summary>
    public string? Label { get; set; }

    public NodeSide Side { get; set; }

    /// <summary>Left out of the suggestions without losing the history.</summary>
    public bool Hidden { get; set; }

    public DateTime CreatedAt { get; set; }

    public UserEntity? User { get; set; }
    public TechniqueEntity? Technique { get; set; }
}

/// <summary>A position the user marked in a roll, in the order marked.</summary>
public class RollStepEntity
{
    public long Id { get; set; }
    public long RollId { get; set; }
    public int Order { get; set; }
    public long NodeId { get; set; }
    public StepOutcome Outcome { get; set; }

    public RollEntity? Roll { get; set; }
    public GameNodeEntity? Node { get; set; }
}

/// <summary>"Point to fix" written at the end of a session and answered in a later one.</summary>
public class FocusPointEntity
{
    public long Id { get; set; }
    public Guid UserId { get; set; }
    public Guid OriginSessionId { get; set; }
    public required string Text { get; set; }
    public DateTime CreatedAt { get; set; }

    /// <summary>Session it was answered in, when the answer came with one.</summary>
    public Guid? ReviewedSessionId { get; set; }

    /// <summary>Null while open.</summary>
    public FocusReview? Review { get; set; }

    public UserEntity? User { get; set; }
    public TrainingSessionEntity? OriginSession { get; set; }
    public TrainingSessionEntity? ReviewedSession { get; set; }
}
